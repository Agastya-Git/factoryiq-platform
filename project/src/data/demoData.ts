function genTelemetry(
  baseTemp: number,
  baseVib: number,
  basePower: number,
  points = 12
): MachineTelemetry[] {
  const readings: MachineTelemetry[] = [];
  for (let i = 0; i < points; i++) {
    const hour = (8 + i) % 24;
    const wobble = Math.sin(i * 1.3) * 1.5;
    readings.push({
      time: `${String(hour).padStart(2, '0')}:00`,
      temperature: Math.round((baseTemp + wobble) * 10) / 10,
      vibration: Math.round((baseVib + Math.sin(i * 0.9) * 0.3) * 100) / 100,
      power: Math.round((basePower + Math.sin(i * 0.7) * 0.8) * 10) / 10,
    });
  }
  return readings;
}

